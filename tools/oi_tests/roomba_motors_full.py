import serial, time
s = serial.Serial('/dev/ttyUSB0', 115200, timeout=1)
def w(*b, wait=0.05): s.write(bytes(b)); s.flush(); time.sleep(wait)
def log(m): print(time.strftime('%H:%M:%S'), m, flush=True)
w(128, wait=0.15); w(130, wait=0.15); w(132, wait=0.15)
w(140, 2, 1, 84, 16); w(140, 3, 2, 84, 10, 88, 10)
w(141, 2, wait=1.0);                  log("FULL mode + marker beep")
w(139, 25, 0, 128, wait=3.0);         log("LEDs (held 3 s)")
w(139, 0, 0, 0, wait=1.0)
w(138, 2, wait=2.0); w(138, 0, wait=1.5); log("vacuum 2 s")
w(138, 1, wait=2.0); w(138, 0, wait=1.5); log("side brush 2 s")
w(138, 4, wait=2.0); w(138, 0, wait=1.5); log("main brush 2 s")
w(141, 3, wait=0.6);                  log("done: two beeps")
s.reset_input_buffer(); w(142, 3, wait=0)
d = s.read(10); log(f"sensor packet 3: {len(d)} bytes {d.hex()}")
w(130, wait=0.05); w(128)
s.close()