#!/usr/bin/env bash
# WSL side of the Isaac Sim closed loop (run as root). Started by twin/isaac/run_closed_loop.ps1:
#   closed_loop.sh start <run_name> [people_engine]   router + OI bridge + robot stack + monitor
#   closed_loop.sh stop                               graceful stop (RTAB-Map saves its database)
#   closed_loop.sh status
# Everything lives in /root/isaacloop/runs/<run_name> (HOME for the web app, test map database, logs);
# ~/maps and ~/.config/roomba_web are never used. RMW zenoh, ROS_DOMAIN_ID 60, router on tcp/0.0.0.0:7447
# (reached from Windows as tcp/127.0.0.1:7447 through WSL's localhost forwarding).
set -uo pipefail
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
WS=${WS:-/root/isaacloop_ws}
BASE=/root/isaacloop
CUR=$BASE/current
export ROS_DOMAIN_ID=${ROS_DOMAIN_ID:-60}
export RMW_IMPLEMENTATION=rmw_zenoh_cpp
export ZENOH_ROUTER_CHECK_ATTEMPTS=0     # nodes wait for the router instead of giving up
export CUDA_HOME=/usr/local/cuda PATH=/usr/local/cuda/bin:$PATH
export CUDA_CACHE_PATH=/root/.nv/ComputeCache CUDA_CACHE_MAXSIZE=4294967296   # nvblox JIT for Blackwell (~30 s once)
export RCUTILS_COLORIZED_OUTPUT=0 PYTHONUNBUFFERED=1

env_ros() {
  set +u
  source /opt/ros/jazzy/setup.bash
  source "$WS/install/setup.bash"
  set -u
}

pids() { cat "$CUR/pids" 2>/dev/null; }

start() {
  local name=${1:-run_$(date +%Y%m%d_%H%M%S)} engine=${2:-yolo11n_384x640_fp16.engine}
  local run=$BASE/runs/$name
  mkdir -p "$run/home/models" "$run/logs"
  ln -sfn "$run" "$CUR"
  : > "$run/pids"
  env_ros
  # the person detector's engine (built by build_engines.sh) at its default path under this HOME
  local eng=$BASE/home/models/$engine
  [ -f "$eng" ] || { echo "missing engine $eng (run build_engines.sh)"; exit 1; }
  ln -sf "$eng" "$run/home/models/yolo11n_384x640_fp16.engine"
  # driver config: the robot's, with the port on the bridge's pty
  python3 - "$WS/install/roomba_bringup/share/roomba_bringup/config/roomba_driver_robot.yaml" "$run" <<'EOF'
import sys, yaml
cfg = yaml.safe_load(open(sys.argv[1]))
cfg['roomba_driver']['ros__parameters']['port'] = sys.argv[2] + '/ttyROOMBA'
open(sys.argv[2] + '/roomba_driver_isaac.yaml', 'w').write(
    '# Generated by closed_loop.sh: the robot config, port on the Isaac OI bridge pty\n' + yaml.safe_dump(cfg, sort_keys=False))
EOF
  if ! ss -ltn | grep -q ':7447 '; then
    setsid -f bash -c "exec ros2 run rmw_zenoh_cpp rmw_zenohd > '$run/logs/zenohd.log' 2>&1" < /dev/null
    sleep 2
  fi
  pgrep -f rmw_zenohd >> "$run/pids"
  setsid -f bash -c "echo \$\$ >> '$run/pids'; exec python3 '$HERE/isaac_roomba.py' --link '$run/ttyROOMBA' --log '$run/logs/serial.jsonl' > '$run/logs/isaac_roomba.log' 2>&1" < /dev/null
  sleep 1
  setsid -f bash -c "echo \$\$ >> '$run/pids'; export HOME='$run/home'; cd '$run'; exec python3 '$WS/scripts/graceful.py' ros2 launch '$HERE/isaac_robot.launch.py' wall_timeout_scale:=${WALL_TIMEOUT_SCALE:-1} \
      camera:=false driver:=true driver_params:='$run/roomba_driver_isaac.yaml' odometry:=cuvslam fusion:=ekf obstacles:=nvblox \
      mode:=mapping database_path:='$run/vslam_test.db' use_sim_time:=true web_port:=18098 foxglove:=false people:=true \
      > '$run/logs/robot_launch.log' 2>&1" < /dev/null
  # Foxglove (ws://localhost:18766; layouts src/roomba_bringup/config/foxglove/explorer_debug.json and
  # twin/isaac/foxglove/closed_loop.json); the 2D-twin runs use 18765
  setsid -f bash -c "echo \$\$ >> '$run/pids'; exec ros2 run foxglove_bridge foxglove_bridge --ros-args -p port:=18766 \
      -p address:=0.0.0.0 -p use_sim_time:=true -p send_buffer_limit:=200000000 > '$run/logs/foxglove.log' 2>&1" < /dev/null
  # sim-side workarounds, off by default since the stack looks around and detects drop-offs itself
  local la=""; [ "${LOOK_AROUND:-0}" = 1 ] && la="--look-around"; [ "${ASSIST:-0}" = 1 ] && la="$la --assist"
  [ "${STAIR_KEEPOUT:-0}" = 1 ] && la="$la --keepout-plan ${PLAN_JSON:-/mnt/e/twin/assets/remodel/floorplan.json}"
  setsid -f bash -c "echo \$\$ >> '$run/pids'; exec python3 '$HERE/cl_monitor.py' --out '$run/monitor' $la --ros-args -p use_sim_time:=true > '$run/logs/monitor.log' 2>&1" < /dev/null
  # CPU of this run's processes only (the 2D-twin agent's stacks share the VM)
  setsid -f bash -c "exec python3 '$HERE/cl_cpu.py' '$run' --every 10 > /dev/null 2>&1" < /dev/null
  # web app password for the viewer (written by the web server on first start)
  for _ in $(seq 60); do
    [ -f "$run/home/.config/roomba_web/initial_password" ] && break
    sleep 1
  done
  [ -f "$run/home/.config/roomba_web/initial_password" ] && cp "$run/home/.config/roomba_web/initial_password" /mnt/e/twin/isaac_watch_password.txt
  echo "started $name in $run"
}

stop() {
  [ -L "$CUR" ] || { echo "nothing running"; return; }
  local run; run=$(readlink -f "$CUR")
  # monitor first (writes its summary), then the launch (graceful: RTAB-Map saves), then bridge + router
  pkill -INT -f "$HERE/cl_monitor.py" 2>/dev/null
  pkill -TERM -f "graceful.py ros2 launch .*isaac_robot.launch.py" 2>/dev/null
  for _ in $(seq 100); do
    pgrep -f "graceful.py ros2 launch .*isaac_robot.launch.py" > /dev/null || break
    sleep 1
  done
  pkill -TERM -f "$HERE/isaac_roomba.py" 2>/dev/null
  pkill -TERM -f "foxglove_bridge.*port:=18766" 2>/dev/null
  pkill -TERM -f "$HERE/cl_cpu.py" 2>/dev/null
  sleep 1
  pkill -TERM -f rmw_zenohd 2>/dev/null
  # anything of this run still alive (by pid list)
  for p in $(pids); do kill -9 "$p" 2>/dev/null; done
  rm -f "$CUR"
  echo "stopped $(basename "$run")"
}

status() {
  [ -L "$CUR" ] && echo "run: $(readlink -f "$CUR")" || echo "no run"
  pgrep -af "rmw_zenohd|isaac_roomba.py|graceful.py ros2 launch|cl_monitor.py|port:=18766" | cut -c1-160
}

case "${1:-status}" in
  start) shift; start "$@" ;;
  stop) stop ;;
  status) status ;;
  *) echo "usage: $0 start [name] [engine] | stop | status"; exit 2 ;;
esac
