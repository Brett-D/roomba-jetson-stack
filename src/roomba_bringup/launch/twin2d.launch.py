"""2D digital twin: the real navigation stack driving a simulated Roomba around the house.

  scripts/run_twin2d.sh scenario:=<file.yaml> out_dir:=/data/twin/twin2d/runs/<name>
  ros2 launch roomba_bringup twin2d.launch.py scenario:=... out_dir:=...   (ROS_DOMAIN_ID of your choice)

twin2d (roomba_rs) stands in for the Roomba, the camera, the localisation and RTAB-Map (see
src/roomba_rs/src/bin/twin2d.rs): it plays the Roomba's Open Interface on a pty, renders the depth
camera and IMU, publishes map -> odom -> base_link and /rtabmap/map (revealed from what the camera
saw), runs the scenario and writes result.json / trajectory.png / timeline.csv / events.jsonl to
out_dir. Everything else is the robot's real stack, as robot.launch.py starts it (rust_nodes:=true):
  roomba_driver on the twin's pty (a generated params file in out_dir: the robot config with only
  the port changed - never the real serial adapter), the camera mount TF, imu_filter_madgwick,
  ignore_zones (zones file in out_dir), nav.launch.py (floor_obstacles, map_gap_filler, Nav2,
  nav_coach, explorer) and the web app on web_port with HOME in out_dir/home (its password file is
  out_dir/home/.config/roomba_web/initial_password), optionally foxglove_bridge.
Not started: camera driver, VIO, vslam_watchdog, RTAB-Map, person detector. Nothing is read from or
written to ~/maps or ~/.config/roomba_web. The launch ends by itself when the run is over
(exit_on_finish:=false keeps everything running for driving it by hand from the web app).
"""
import os

import yaml
from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import (DeclareLaunchArgument, EmitEvent, IncludeLaunchDescription, LogInfo, OpaqueFunction,
                            RegisterEventHandler)
from launch.event_handlers import OnProcessExit
from launch.events import Shutdown
from launch.launch_description_sources import PythonLaunchDescriptionSource
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node, SetParameter

DEFAULT_WORLD = '/data/twin/twin2d/world/house.yaml'


def _setup(context):
    lc = lambda name: LaunchConfiguration(name).perform(context)  # noqa: E731
    bringup = get_package_share_directory('roomba_bringup')
    out_dir = os.path.abspath(os.path.expanduser(lc('out_dir')))
    for forbidden in (os.path.expanduser('~/maps'), os.path.expanduser('~/.config/roomba_web')):
        if out_dir == forbidden or out_dir.startswith(forbidden + os.sep):
            raise RuntimeError(f'out_dir must not be inside {forbidden}')
    os.makedirs(out_dir, exist_ok=True)
    scenario = os.path.abspath(os.path.expanduser(lc('scenario'))) if lc('scenario') else ''
    scenario_data = {}
    if scenario:
        with open(scenario) as f:
            scenario_data = yaml.safe_load(f) or {}
    rust = lc('rust_nodes') == 'true'
    pkg = 'roomba_rs' if rust else 'roomba_perception'

    # The driver's port is the twin's pty. Only this generated file is passed: rclrs gives a
    # node-specific params-file entry priority over a -p override, so a second source for the port
    # could silently open the real serial adapter.
    pty = os.path.join(out_dir, 'ttyROOMBA')
    with open(lc('driver_params')) as f:
        driver_cfg = yaml.safe_load(f)
    driver_cfg.setdefault('roomba_driver', {}).setdefault('ros__parameters', {})['port'] = pty
    if driver_cfg['roomba_driver']['ros__parameters']['port'].startswith('/dev/'):
        raise RuntimeError('refusing to give the driver a /dev port in the twin')
    driver_params = os.path.join(out_dir, 'roomba_driver_twin.yaml')
    with open(driver_params, 'w') as f:
        f.write('# Generated by twin2d.launch.py: the robot config with the port on the twin\'s pty.\n')
        yaml.safe_dump(driver_cfg, f, sort_keys=False)

    # The twin's depth is exact (depth_scale 1): the floor is cam_z below the lens. With the real
    # camera's 15 % short depth (sensors.depth_scale 0.85) it reads ~0.11 m, as calibrated on the robot.
    floor_height = lc('floor_height')
    if not floor_height:
        scale = float((scenario_data.get('sensors') or {}).get('depth_scale', 1.0))
        floor_height = str(round(float(lc('cam_z')) * scale, 4))
    home = os.path.join(out_dir, 'home')
    os.makedirs(home, exist_ok=True)

    twin = Node(
        package='roomba_rs', executable='twin2d', name='twin2d', output='screen',
        parameters=[{
            'world': os.path.expanduser(lc('world')),
            'scenario': scenario,
            'out_dir': out_dir,
            'pty_link': pty,
            'cam_x': float(lc('cam_x')), 'cam_y': float(lc('cam_y')), 'cam_z': float(lc('cam_z')),
            'cam_pitch': float(lc('cam_pitch')),
            'seed': int(lc('seed')),
            'exit_on_finish': lc('exit_on_finish') == 'true',
        }],
    )
    actions = [
        LogInfo(msg=f'[twin2d] scenario={scenario or "(default exploration)"} out_dir={out_dir} '
                    f'floor_height={floor_height} web=http://<jetson>:{lc("web_port")}/'),
        twin,
        Node(package='tf2_ros', executable='static_transform_publisher', name='camera_mount_tf',
             arguments=['--x', lc('cam_x'), '--y', lc('cam_y'), '--z', lc('cam_z'),
                        '--roll', '0', '--pitch', lc('cam_pitch'), '--yaw', '0',
                        '--frame-id', 'base_link', '--child-frame-id', 'camera_link']),
        Node(package='imu_filter_madgwick', executable='imu_filter_madgwick_node', name='imu_filter',
             namespace='camera', parameters=[{'use_mag': False, 'publish_tf': False, 'world_frame': 'enu'}],
             remappings=[('imu/data_raw', '/camera/imu/data_raw'), ('imu/data', '/camera/imu/data')]),
        Node(package=pkg, executable='ignore_zones', name='ignore_zones', namespace='perception', output='screen',
             parameters=[{'zones_file': os.path.join(out_dir, 'zones.json'), 'clear_on_start': True}]),
    ]
    if lc('driver') == 'true':
        actions.append(Node(package='roomba_rs' if rust else 'roomba_driver', executable='roomba_driver',
                            name='roomba_driver', output='screen', parameters=[driver_params]))
    if lc('nav') == 'true':
        actions.append(IncludeLaunchDescription(
            PythonLaunchDescriptionSource(os.path.join(bringup, 'launch', 'nav.launch.py')),
            launch_arguments=[
                ('params_file', lc('nav_params')),
                ('base_frame', 'base_link'),
                ('robot_mode', 'true'),
                ('rust_nodes', lc('rust_nodes')),
                ('fallback_camera_height_m', floor_height),
                ('fixed_camera_height_m', floor_height),
            ]))
    if lc('web') == 'true':
        actions.append(Node(package='roomba_rs' if rust else 'roomba_web', executable='web_server', name='web_server',
                            output='screen', additional_env={'HOME': home},
                            parameters=[{'port': int(lc('web_port')), 'localization': False,
                                         'base_frame': 'base_link', 'floor_grid': True}]))
    if lc('foxglove') == 'true':
        actions.append(Node(package='foxglove_bridge', executable='foxglove_bridge', name='foxglove_bridge',
                            parameters=[{'port': int(lc('foxglove_port')), 'topic_whitelist': ['.*']}]))
    if lc('exit_on_finish') == 'true':
        actions.append(RegisterEventHandler(OnProcessExit(
            target_action=twin, on_exit=[EmitEvent(event=Shutdown(reason='twin2d run over'))])))
    return actions


def generate_launch_description():
    bringup = get_package_share_directory('roomba_bringup')
    args = [
        DeclareLaunchArgument('scenario', default_value='',
                              description='Scenario YAML (config/twin2d/*.yaml); empty: explore from the map origin'),
        DeclareLaunchArgument('world', default_value=DEFAULT_WORLD,
                              description='Floor plan (map YAML + PGM, tools/twin2d_world.py)'),
        DeclareLaunchArgument('out_dir', default_value='/data/twin/twin2d/runs/manual',
                              description='Results, the pty, the zones file and the web app HOME go here'),
        DeclareLaunchArgument('seed', default_value='-1', description='Overrides the scenario seed (>= 0)'),
        DeclareLaunchArgument('exit_on_finish', default_value='true',
                              description='End the launch when the run is over'),
        DeclareLaunchArgument('rust_nodes', default_value='true'),
        DeclareLaunchArgument('driver', default_value='true'),
        DeclareLaunchArgument('nav', default_value='true'),
        DeclareLaunchArgument('web', default_value='true'),
        DeclareLaunchArgument('web_port', default_value='18097'),
        DeclareLaunchArgument('foxglove', default_value='false'),
        DeclareLaunchArgument('foxglove_port', default_value='18765'),
        DeclareLaunchArgument('driver_params', default_value=os.path.join(bringup, 'config', 'roomba_driver_robot.yaml')),
        DeclareLaunchArgument('nav_params', default_value=os.path.join(bringup, 'config', 'nav2_robot.yaml')),
        DeclareLaunchArgument('cam_x', default_value='0.153'),
        DeclareLaunchArgument('cam_y', default_value='0.0'),
        DeclareLaunchArgument('cam_z', default_value='0.13'),
        DeclareLaunchArgument('cam_pitch', default_value='0.0'),
        DeclareLaunchArgument('floor_height', default_value='',
                              description='floor_obstacles camera height (empty: cam_z x the scenario depth_scale)'),
        # A run must stop quickly; nothing here saves a database on shutdown.
        DeclareLaunchArgument('sigkill_timeout', default_value='10'),
        SetParameter(name='use_sim_time', value=False),
    ]
    return LaunchDescription(args + [OpaqueFunction(function=_setup)])
